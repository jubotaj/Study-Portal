export function enrichProgramMetadata(prog: Program): Program {
  const rank = Number(prog.qsRank) || 50;
  const computedMinGpa =
    rank <= 5 ? 3.8 : rank <= 15 ? 3.65 : rank <= 35 ? 3.45 : rank <= 65 ? 3.25 : 3.05;

  const docs: string[] = [];
  if (prog.degreeLevel === 'Bachelor') {
    docs.push('Official High School / Secondary Transcripts & Diploma');
    docs.push('Personal Statement / Admissions Essay');
    docs.push('2 Academic Reference Letters');
  } else if (prog.degreeLevel === 'PhD') {
    docs.push('Official Bachelor & Master Academic Transcripts');
    docs.push('PhD Research Proposal (2-4 pages)');
    docs.push('3 Academic Recommendation Letters');
    docs.push('Academic CV & Publications Summary');
    docs.push('Prospective Faculty Supervisor Endorsement');
  } else {
    docs.push('Official Bachelor Academic Transcripts & Degree Certificate');
    docs.push('Statement of Purpose (SOP)');
    docs.push('2 Academic or Professional Recommendation Letters');
    docs.push('Curriculum Vitae (CV / Resume)');
  }

  docs.push(`English Proficiency Proof (${prog.language.includes('English') ? 'IELTS 6.5+ / TOEFL 90+' : prog.language})`);
  docs.push('Valid Passport Copy (Biographic Page)');

  const c = prog.country.toLowerCase();
  if (c.includes('germany')) {
    docs.push('uni-assist VPD / APS Certificate (if required by home country)');
  } else if (c.includes('canada')) {
    docs.push('Canadian Study Permit Financial Proof (Tuition + CAD $20,635 living funds)');
  } else if (c.includes('united states')) {
    docs.push('GRE / GMAT Official Score Report (department-dependent) & I-20 Financial Affidavit');
  } else if (c.includes('switzerland')) {
    docs.push('Detailed Course / Module Syllabus Descriptions (for credit equivalence)');
  } else if (c.includes('japan')) {
    docs.push('Research Plan & Lab Acceptance / MEXT Pre-Approval (if applicable)');
  } else if (c.includes('korea')) {
    docs.push('Apostilled / Consular-Verified Degree Certificate & Family Nationality Proof');
  } else if (c.includes('australia')) {
    docs.push('Genuine Student (GS) Statement & OSHC Health Cover Declaration');
  }

  const fallbackQuery = encodeURIComponent(`${prog.university} official admissions portal apply`);
  const portalUrl =
    prog.admissionsPortalUrl ||
    PORTAL_URL_BY_ID[prog.id] ||
    `https://www.google.com/search?q=${fallbackQuery}`;

  return {
    ...prog,
    admissionsPortalUrl: portalUrl,
    minGpaRecommended: prog.minGpaRecommended ?? computedMinGpa,
    requiredDocuments:
      prog.requiredDocuments && prog.requiredDocuments.length > 0 ? prog.requiredDocuments : docs,
  };
}

